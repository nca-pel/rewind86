type Pix = (x: number, y: number) => boolean;

function fromFn(fn: Pix): Rows {
  const rows: string[] = [];
  for (let y = 0; y < 8; y++) {
    let r = '';
    for (let x = 0; x < 8; x++) r += fn(x, y) ? '#' : '.';
    rows.push(r);
  }
  return rows;
}

const or =
  (...fs: Pix[]): Pix =>
  (x, y) =>
    fs.some((f) => f(x, y));
const rows =
  (a: number, b: number): Pix =>
  (_x, y) =>
    y >= a && y <= b;
const cols =
  (a: number, b: number): Pix =>
  (x) =>
    x >= a && x <= b;
const rect =
  (x0: number, y0: number, x1: number, y1: number): Pix =>
  (x, y) =>
    x >= x0 && x <= x1 && y >= y0 && y <= y1;
const checker: Pix = (x, y) => (x + y) % 2 === 0;

/** Mittellinien (2 Pixel breit) für Rahmenzeichen */
