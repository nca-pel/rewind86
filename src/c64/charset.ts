// --------------------------------------------------------------------------- Zusammenbau

/** Zeichen für Bildschirmcodes 0–63 (in beiden Sätzen gleich, außer Buchstaben) */
const BASE_ORDER = '@ABCDEFGHIJKLMNOPQRSTUVWXYZ[£]↑← !"#$%&\'()*+,-./0123456789:;<=>?';

function glyphFor(set: CharsetId, code: number): Rows {
  if (code < 64) {
    const ch = BASE_ORDER[code];
    if (set === 'lower' && code >= 1 && code <= 26) return LOWER[ch.toLowerCase()];
    return UPPER[ch];
  }
  if (set === 'lower') {
    if (code >= 65 && code <= 90) return UPPER[String.fromCharCode(code)];
    if (GRAPHICS_LOWER[code]) return GRAPHICS_LOWER[code];
  }
  return GRAPHICS_UPPER[code];
}

function encode(r: Rows): number[] {
  return r.map((row) => [...row].reduce((b, c, i) => (c === '#' ? b | (0x80 >> i) : b), 0));
}

/**
 * Baut einen Zeichengenerator mit 256 × 8 Bytes (Bit 7 = linkes Pixel), wie ihn der Videochip
 * erwartet: Codes 128–255 sind die invertierten Codes 0–127.
 */
export function buildCharset(set: CharsetId): Uint8Array {
  const out = new Uint8Array(256 * 8);
  for (let code = 0; code < 128; code++) {
    const bytes = encode(glyphFor(set, code));
    for (let y = 0; y < 8; y++) {
      out[code * 8 + y] = bytes[y];
      out[(code + 128) * 8 + y] = bytes[y] ^ 0xff;
    }
  }
  return out;
}

const cache: Partial<Record<CharsetId, Uint8Array>> = {};

export function charset(set: CharsetId): Uint8Array {
  return (cache[set] ??= buildCharset(set));
}
