/**
 * Eigener 8×8-Zeichensatz im Stil der Heimcomputer der 1980er-Jahre.
 *
 * Alle Glyphen sind für dieses Projekt neu gezeichnet bzw. aus einfachen geometrischen Regeln
 * erzeugt (Linien, Blöcke, Raster). Es werden KEINE Daten aus einem Zeichensatz-ROM verwendet.
 * Gestaltungsprinzip wie bei Geräten, die an Fernseher angeschlossen wurden: senkrechte Striche
 * sind zwei Pixel breit, waagerechte einen Pixel hoch, die unterste Zeile bleibt für Abstand frei.
 *
 * Belegung nach Bildschirmcode (nicht ASCII/PETSCII):
 *   0–63    @, A–Z, [ £ ] ↑ ←, Leerzeichen, Satzzeichen, Ziffern
 *   64–127  Blockgrafik (im Groß-/Kleinschrift-Satz: 65–90 = Großbuchstaben)
 *   128–255 dieselben Zeichen invertiert (Revers-Darstellung)
 * Satz „upper“ = Großschrift/Grafik (Einschaltzustand), „lower“ = Klein-/Großschrift.
 */

export type CharsetId = 'upper' | 'lower';

type Rows = readonly string[];

function g(...rows: string[]): Rows {
  if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error('Glyphe muss 8×8 sein');
  return rows;
}

