const midV = cols(3, 4);
const halfH = (side: 'l' | 'r'): Pix => (side === 'l' ? rect(0, 3, 4, 4) : rect(3, 3, 7, 4));
const halfV = (side: 't' | 'b'): Pix => (side === 't' ? rect(3, 0, 4, 4) : rect(3, 3, 4, 7));

